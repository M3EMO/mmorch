/// Repo con una clave sintética en un archivo de configuración.
fn repo_con_secreto() -> tempfile::TempDir {
    let repo = repo_minimo();
    fs::write(
        repo.path().join("config.env"),
        format!("AWS_ACCESS_KEY_ID={SECRETO}\n"),
    )
    .expect("escribe config.env");
    repo
}

#[test]
fn sonda_real_ninguna_herramienta_de_la_imagen_da_sin_veredicto_por_ausencia() {
    let imagen = imagen_rust();
    asegurar_imagen(&imagen);
    let repo = repo_minimo();
    let vacio = tempfile::tempdir().expect("temp dir");
    let base = base_rustsec(&vacio);
    let cache = cache_rust();
    let ej = ejecutor_rust(&imagen, repo.path(), Some(&base), cache.path());
    let tarea = tarea_rust(Some(r#"echo "{\"ops_s\": 9000}""#));
    let resultados = [
        gitleaks(&ej, &tarea),
        cargo_audit(&ej, &tarea, repo.path()),
        clippy(&ej, &tarea),
        eficiencia(&ej, &tarea),
    ];
    for r in &resultados {
        let motivo = r.motivo.clone().unwrap_or_default();
        assert!(
            !motivo.contains("no está en la imagen de evaluación"),
            "{:?}: herramienta ausente: {motivo}",
            r.dimension
        );
        assert!(
            r.valor.is_some(),
            "{:?}: sin veredicto: {motivo}",
            r.dimension
        );
    }
    assert_eq!(resultados[0].dimension, Dimension::Seguridad);
    assert_eq!(resultados[1].dimension, Dimension::Seguridad);
    assert_eq!(resultados[2].dimension, Dimension::Estructura);
}

#[test]
fn sonda_real_gitleaks_con_clave_sintetica_da_hallazgo_sin_el_secreto() {
    let imagen = imagen_rust();
    asegurar_imagen(&imagen);
    let repo = repo_con_secreto();
    let ej = ejecutor(&imagen, repo.path(), None);
    let r = gitleaks(&ej, &tarea_rust(None));
    assert_eq!(r.motivo, None);
    assert!(
        !r.hallazgos.is_empty(),
        "gitleaks no halló la clave sintética"
    );
    assert!(r.hallazgos.iter().all(|h| h.severidad == 3));
    // El secreto no entra a ningún campo del resultado.
    let texto = format!("{:?} {:?}", r.motivo, r.hallazgos);
    assert!(!texto.contains(SECRETO), "el resultado copió el secreto");
}

/// Base de RustSec real. Si falta, el test falla con mensaje: no pasa en silencio.
fn base_rustsec_real() -> PathBuf {
    let home = std::env::var("HOME").expect("HOME sin definir");
    let base = PathBuf::from(home).join(".local/share/root/cache/rustsec");
    assert!(
        base.is_dir(),
        "falta la base de RustSec en {}: sin ella no hay prueba real de cargo audit",
        base.display()
    );
    base
}

