#[test]
fn sonda_real_hadolint_sobre_from_latest_da_hallazgo() {
    let imagen = imagen_rust();
    asegurar_imagen(&imagen);
    let repo = repo_minimo();
    fs::write(
        repo.path().join("Dockerfile"),
        "FROM python:latest\nRUN echo hola\n",
    )
    .expect("escribe Dockerfile");
    let ej = ejecutor(&imagen, repo.path(), None);
    let resultados = sondas_configs(repo.path(), &ej, &tarea_rust(None));
    let de_hadolint: Vec<_> = resultados
        .iter()
        .flat_map(|r| r.hallazgos.iter())
        .filter(|h| h.fuente == Fuente::Sonda("hadolint".into()))
        .collect();
    assert!(
        !de_hadolint.is_empty(),
        "hadolint no halló nada: {resultados:?}"
    );
    for r in &resultados {
        let motivo = r.motivo.clone().unwrap_or_default();
        assert!(
            !motivo.contains("no está en la imagen de evaluación"),
            "herramienta ausente: {motivo}"
        );
    }
}

#[test]
fn sonda_real_clippy_eq_op_da_hallazgo() {
    let imagen = imagen_rust();
    asegurar_imagen(&imagen);
    let repo = repo_minimo();
    // `x == x` es `clippy::eq_op`, del grupo correctness.
    fs::write(
        repo.path().join("src/lib.rs"),
        "pub fn f(x: u8) -> bool { x == x }\n",
    )
    .expect("escribe lib.rs");
    let cache = cache_rust();
    let ej = ejecutor_rust(&imagen, repo.path(), None, cache.path());
    let r = clippy(&ej, &tarea_rust(None));
    assert_eq!(r.motivo, None, "clippy sin veredicto");
    assert!(
        r.hallazgos
            .iter()
            .any(|h| h.fuente == Fuente::Sonda("clippy".into())),
        "clippy no halló eq_op: {:?}",
        r.hallazgos
    );
}

